EFFECT_KEYS = (
    "domains", "interests", "knowledge", "skills", "abilities",
    "work_activities", "work_styles", "technology", "job_zone",
)


def opt(option_id: str, text: str, **effects: Any) -> Dict[str, Any]:
    unknown = set(effects) - set(EFFECT_KEYS)
    if unknown:
        raise ValueError(f"Unknown effect keys on {option_id}: {sorted(unknown)}")
    return {"option_id": option_id, "text": text, "effects": effects}


def q(
    question_id: str,
    text: str,
    options: List[Dict[str, Any]],
    section: str = "core",
    domain: Optional[str] = None,
    deep_scan: bool = False,
) -> Dict[str, Any]:
    return {
        "question_id": question_id,
        "text": text,
        "section": section,
        "domain": domain,
        "deep_scan": deep_scan,
        "options": options,
    }


