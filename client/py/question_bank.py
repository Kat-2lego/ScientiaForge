# How many domain questions to serve, by how many domains were selected. Total
# questionnaire length stays in the 17-23 range whatever the selection.
QUESTIONS_PER_DOMAIN = {1: 9, 2: 6, 3: 5}
DEEP_SCAN_QUESTION_COUNT = 8


def build_question_set(
    domains: List[str], deep_scan_enabled: bool
) -> List[Dict[str, Any]]:
    """Deterministic question set for this configuration (§35)."""
    selected = [d for d in domains if d in DOMAIN_QUESTIONS]
    per_domain = QUESTIONS_PER_DOMAIN.get(len(selected), 5)

    core = list(CORE_QUESTIONS)
    deep = list(DEEP_SCAN_QUESTIONS[:DEEP_SCAN_QUESTION_COUNT]) if deep_scan_enabled else []

    # Round-robin across the selected domains, so someone who picked three
    # domains alternates between them instead of answering every technology
    # question before seeing a single design one.
    pools = {d: list(DOMAIN_QUESTIONS[d][:per_domain]) for d in selected}
    ordered: List[Dict[str, Any]] = []
    while any(pools.values()):
        for domain in selected:
            if pools[domain]:
                ordered.append(pools[domain].pop(0))

    # Trim domain questions to keep the whole run inside the ceiling. Core and
    # deep-scan questions are never dropped: they carry the dimensions the
    # matching engine needs most.
    budget = max(config.MAX_QUESTIONS - len(core) - len(deep), 0)
    if selected:
        budget = max(budget, config.MIN_DOMAIN_QUESTIONS * len(selected))
    return core + ordered[:budget] + deep


# The fifteen broader domains live in their own module to keep this file a
# manageable size; the format is identical.
from question_bank_domains import EXTRA_DOMAIN_QUESTIONS  # noqa: E402

for _domain, _questions in EXTRA_DOMAIN_QUESTIONS.items():
    DOMAIN_QUESTIONS.setdefault(_domain, _questions)


def index_questions() -> Dict[str, Dict[str, Any]]:
    """question_id -> question, across the whole bank."""
    index: Dict[str, Dict[str, Any]] = {}
    for question in (
        CORE_QUESTIONS
        + DEEP_SCAN_QUESTIONS
        + [item for group in DOMAIN_QUESTIONS.values() for item in group]
    ):
        index[question["question_id"]] = question
    return index


QUESTION_INDEX: Dict[str, Dict[str, Any]] = index_questions()


def lookup_option(question_id: str, option_id: str) -> Optional[Dict[str, Any]]:
    question = QUESTION_INDEX.get(question_id)
    if not question:
        return None
    for option in question["options"]:
        if option["option_id"] == option_id:
            return option
    return None
